<script setup lang="ts">
// SPIKE (#13): add a passkey and turn on TOTP.
import { Head, router, useForm } from '@inertiajs/vue3';
import { usePasskeyRegister } from '@laravel/passkeys/vue';
import { ref } from 'vue';

defineProps<{
    user: { name: string; email: string };
    passkeys: { id: number; name: string; created_at: string }[];
    totp: { enabled: boolean; confirmed: boolean; qrSvg: string | null };
}>();

const passkeyName = ref('');
const {
    register,
    isLoading,
    error: passkeyError,
} = usePasskeyRegister({
    onSuccess: () => {
        passkeyName.value = '';
        router.reload();
    },
});

const confirmForm = useForm({ code: '' });

const enableTotp = () =>
    router.post(
        '/user/two-factor-authentication',
        {},
        { preserveScroll: true },
    );
const confirmTotp = () =>
    confirmForm.post('/user/confirmed-two-factor-authentication', {
        preserveScroll: true,
    });
const signOut = () => router.post('/logout');
</script>

<template>
    <Head title="Security" />

    <main>
        <h1>Security</h1>
        <p>Signed in as {{ user.email }}</p>

        <h2>Passkeys</h2>
        <ul>
            <li v-for="passkey in passkeys" :key="passkey.id">
                {{ passkey.name }}
            </li>
        </ul>
        <form @submit.prevent="register(passkeyName)">
            <p>
                <label for="passkey-name">Name for the new passkey</label>
                <input id="passkey-name" v-model="passkeyName" required />
            </p>
            <button type="submit" :disabled="isLoading || !passkeyName">
                Add a passkey
            </button>
        </form>
        <p v-if="passkeyError" role="alert">{{ passkeyError }}</p>

        <h2>Authenticator app</h2>
        <p v-if="totp.confirmed">On</p>
        <button v-else-if="!totp.enabled" type="button" @click="enableTotp">
            Set up an authenticator app
        </button>
        <form v-else @submit.prevent="confirmTotp">
            <!-- eslint-disable-next-line vue/no-v-html -- SVG generated by the server from the user's own secret -->
            <div aria-hidden="true" v-html="totp.qrSvg" />
            <p>
                <label for="totp-code">Code from your authenticator app</label>
                <input
                    id="totp-code"
                    v-model="confirmForm.code"
                    inputmode="numeric"
                    autocomplete="one-time-code"
                />
            </p>
            <button type="submit">Turn on</button>
        </form>

        <p><button type="button" @click="signOut">Sign out</button></p>
    </main>
</template>
